/*
    LGD / Census state and district codes.
    ------------------------------------------------------------------------
    Source: "All Districts of India" (784 districts, 36 states and UTs),
    supplied as the authoritative code list.

    Why this replaces the earlier seed: the portal receives a Udyam record whose
    address carries these official codes. Matching on district *name* is not
    safe — names are spelt several ways, several states reuse a name, and
    districts get renamed. The code is the stable key.

    States are matched to the existing master.State rows by name so their
    StateId (and every enterprise already pointing at it) is preserved; only the
    Code column is corrected. Districts are merged on (StateId, Code).

    Idempotent: re-running only updates.
*/

SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

/*
    State names differ between the portal's seed and the official list in three
    ways: case, "And" vs "and", and a leading "The" ("The Dadra And Nagar Haveli
    And Daman And Diu"). Matching on the raw string silently creates a duplicate
    state, so the comparison is normalised.
*/
CREATE OR ALTER FUNCTION dbo.fn_NormaliseStateName (@name nvarchar(200))
RETURNS nvarchar(200)
WITH SCHEMABINDING
AS
BEGIN
    DECLARE @n nvarchar(200) = LTRIM(RTRIM(LOWER(@name)));

    IF LEFT(@n, 4) = 'the ' SET @n = LTRIM(SUBSTRING(@n, 5, 200));

    SET @n = REPLACE(@n, ' and ', ' & ');
    SET @n = REPLACE(@n, '  ', ' ');

    RETURN @n;
END;
GO

