-- A previous run of this script (before the name was normalised) may have
-- created a second row for the same state. Fold it back: move its districts to
-- the original, then remove it.
DECLARE @dupes TABLE (KeepId smallint, DropId smallint);

INSERT INTO @dupes (KeepId, DropId)
SELECT MIN(s.StateId), MAX(s.StateId)
FROM   master.State AS s
GROUP  BY dbo.fn_NormaliseStateName(s.Name)
HAVING COUNT(*) > 1;

UPDATE d
SET    d.StateId = x.KeepId
FROM   master.District AS d
INNER JOIN @dupes AS x ON x.DropId = d.StateId
WHERE  NOT EXISTS
(
    SELECT 1 FROM master.District AS k
    WHERE k.StateId = x.KeepId AND LOWER(k.Name) = LOWER(d.Name)
);

DELETE d
FROM   master.District AS d
INNER JOIN @dupes AS x ON x.DropId = d.StateId;

UPDATE s
SET    s.Code = COALESCE(dup.Code, s.Code)
FROM   master.State AS s
INNER JOIN @dupes AS x ON x.KeepId = s.StateId
INNER JOIN master.State AS dup ON dup.StateId = x.DropId;

DELETE s
FROM   master.State AS s
INNER JOIN @dupes AS x ON x.DropId = s.StateId;

-- ------------------------------------------------------------- states ---
-- Names differ in case and in "And"/"and", so the match is case-insensitive
-- and normalises the conjunction.
UPDATE s
SET    s.Code = x.StateCode
FROM   master.State AS s
INNER JOIN
(
    SELECT DISTINCT StateCode, StateName FROM #Src
) AS x
    ON dbo.fn_NormaliseStateName(s.Name) = dbo.fn_NormaliseStateName(x.StateName);

-- Anything in the file the portal does not yet know about.
INSERT INTO master.State (Code, Name, IsUnionTerritory, IsNorthEastern, IsActive)
SELECT DISTINCT x.StateCode, x.StateName, 0, 0, 1
FROM   (SELECT DISTINCT StateCode, StateName FROM #Src) AS x
WHERE  NOT EXISTS
(
    SELECT 1 FROM master.State AS s
    WHERE dbo.fn_NormaliseStateName(s.Name) = dbo.fn_NormaliseStateName(x.StateName)
       OR s.Code = x.StateCode
);

-- ---------------------------------------------------------- districts ---
-- master.District carries UQ_District on (StateId, Name), and the earlier seed
-- already holds districts under their own codes. So the official code is first
-- stamped onto the row that already bears that name, and only what remains is
-- inserted — otherwise every pre-existing district would collide on its name.
WITH Official AS
(
    SELECT s.StateId, x.DistrictCode, x.DistrictName
    FROM   #Src AS x
    INNER JOIN master.State AS s ON s.Code = x.StateCode
)
UPDATE d
SET    d.Code = o.DistrictCode,
       d.Name = o.DistrictName,
       d.IsActive = 1
FROM   master.District AS d
INNER JOIN Official AS o
    ON  o.StateId = d.StateId
    AND LOWER(o.DistrictName) = LOWER(d.Name);

-- Now the genuinely new ones.
INSERT INTO master.District (StateId, Code, Name, IsActive)
SELECT s.StateId, x.DistrictCode, x.DistrictName, 1
FROM   #Src AS x
INNER JOIN master.State AS s ON s.Code = x.StateCode
WHERE  NOT EXISTS
(
    SELECT 1 FROM master.District AS d
    WHERE d.StateId = s.StateId
      AND (d.Code = x.DistrictCode OR LOWER(d.Name) = LOWER(x.DistrictName))
);

-- Districts seeded earlier without an official code. They are deactivated
-- rather than deleted: enterprises may already reference them.
UPDATE master.District
SET    IsActive = 0
WHERE  Code IS NULL OR Code NOT IN (SELECT DistrictCode FROM #Src);

DROP TABLE #Src;

COMMIT TRANSACTION;

